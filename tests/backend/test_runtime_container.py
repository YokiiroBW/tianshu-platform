"""The production static container: what can be proven here, and what is explicitly not proven.

This suite never claims a container works because a Dockerfile exists. Everything it can check
without a container runtime - the image definition, the ignore rules, the deployment template, and
the console served from the built assets - it checks against the real files. Everything that needs
a container runtime is skipped with a reason and is reported as unverified in the handoff.
"""

