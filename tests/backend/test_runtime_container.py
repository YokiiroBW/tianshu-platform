@unittest.skipUnless(
    web_build_available(), "apps/web/dist is not built; the served console is unverified"
)
class ServedConsoleTests(unittest.IsolatedAsyncioTestCase):
    """The console as the container actually serves it: the real build, over real TLS."""

    async def asyncSetUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.env = patch.dict(os.environ, environment(), clear=False)
        self.env.start()
        self.addCleanup(self.env.stop)
        self.addCleanup(diagnostics.reset)
        self.settings = runtime_settings(self.temp.name, static=str(WEB_BUILD))
        self.platform = Platform(self.settings)
        self.sink = diagnostics.Diagnostics(self.settings["diagnostics"]["log_directory"])
        diagnostics.activate(self.sink)
        self.addCleanup(self.sink.close, 2.0)
        context = ssl.SSLContext(ssl.PROTOCOL_TLS_SERVER)
        context.load_cert_chain(
            self.settings["tls"]["certificate_file"], self.settings["tls"]["private_key_file"]
        )
        self.runner, self.url = await start_server(create_app(self.platform), tls=context)
        self.addAsyncCleanup(self.runner.cleanup)
        # The console refuses any request whose Host is not its configured origin - that guard is
        # the point of the same-origin console, so the test tells the deployment the origin it was
        # actually reached on rather than weakening the guard.
        self.platform.settings["web"]["origin"] = self.url
        self.client = aiohttp.ClientSession(
            trust_env=False,
            timeout=aiohttp.ClientTimeout(total=10),
            connector=aiohttp.TCPConnector(
                ssl=ssl.create_default_context(cafile=self.settings["tls"]["certificate_file"])
            ),
        )
        self.addAsyncCleanup(self.client.close)

    async def test_the_real_build_is_served_with_the_documented_security_headers(self):
        async with self.client.get(self.url + "/") as response:
            self.assertEqual(response.status, 200)
            self.assertIn("frame-ancestors 'none'", response.headers["Content-Security-Policy"])
            self.assertEqual(response.headers["X-Content-Type-Options"], "nosniff")
            body = await response.text()
        self.assertIn('<div id="root"', body)

    async def test_the_entry_points_own_assets_are_really_served(self):
        async with self.client.get(self.url + "/") as response:
            html = await response.text()
        references = runtime_health.ASSET_REFERENCE.findall(html)
        self.assertTrue(references, "the built entry point references no asset")
        for reference in references:
            async with self.client.get(self.url + reference) as response:
                self.assertEqual(response.status, 200, reference)
                self.assertTrue(await response.read())

    async def test_the_static_container_needs_no_database_and_no_contract_to_answer_liveness(self):
        async with self.client.get(self.url + "/health/live") as response:
            self.assertEqual(response.status, 200)
            self.assertEqual(await response.json(), {"status": "alive"})

    async def test_a_client_without_the_readiness_credential_learns_nothing(self):
        async with self.client.get(self.url + "/health/ready") as response:
            self.assertEqual(response.status, 401)
            self.assertEqual(await response.json(), {"code": "unauthorized"})

    async def test_an_unknown_path_is_not_a_directory_listing(self):
        for path in ("/../Dockerfile", "/deploy/platform/settings.example.json", "/.git/config"):
            async with self.client.get(self.url + path) as response:
                self.assertIn(response.status, (400, 403, 404), path)
                self.assertNotIn("scrypt-v1", await response.text())

    async def test_the_console_is_served_over_verified_tls_and_stays_ready(self):
        async with self.client.get(
            self.url + "/health/ready", headers={"Authorization": "Bearer " + READY_TOKEN}
        ) as response:
            document = await response.json()
        self.assertEqual(response.status, 200, document)
        self.assertEqual(document["checks"]["web_static"], "ok")
        self.assertEqual(document["status"], "ready")

    async def test_serving_the_console_is_logged_once_and_probes_are_not_logged_at_all(self):
        await self.client.get(self.url + "/health/live")
        await self.client.get(self.url + "/health/live")
        await self.client.get(self.url + "/")
        self.sink.flush()
        events = read_events(self.settings["diagnostics"]["log_directory"])
        names = [record["event"] for record in events]
        # Every business request is registered in full and never sampled; the two probe requests
        # above left nothing behind, because a probe that logged would be a probe that writes.
        self.assertEqual(names.count("http.request.started"), 1)
        self.assertEqual(names.count("http.request.finished"), 1)
        for record in events:
            self.assertNotIn("/health/", json.dumps(record))


class DocumentationTests(unittest.TestCase):
    """The rollout a reviewer would follow must match the artifact it describes."""

    def setUp(self):
        if not DEPLOYMENT_DOC.is_file():
            self.skipTest("docs/platform/deployment.md is not written yet")
        self.doc = DEPLOYMENT_DOC.read_text(encoding="utf-8")
        self.dockerfile = DOCKERFILE.read_text(encoding="utf-8")

    def test_the_documented_commands_name_the_real_artifact(self):
        self.assertIn("docker build", self.doc)
        self.assertIn("docker run", self.doc)
        self.assertIn("preflight", self.doc)

    def test_the_documented_port_and_health_paths_match_the_image(self):
        self.assertIn("8443", self.doc)
        self.assertIn("/health/live", self.doc)
        self.assertIn("/health/ready", self.doc)
        self.assertIn("8443", self.dockerfile)

    def test_the_documented_readiness_credential_is_the_one_the_image_reads(self):
        self.assertIn(READY_TOKEN_ENV, self.doc)
        self.assertIn(READY_TOKEN_ENV, self.dockerfile + SETTINGS_EXAMPLE.read_text("utf-8"))

    def test_the_rollout_is_explicit_about_what_was_not_executed_here(self):
        self.assertIn("未验证", self.doc)
        self.assertIn("needs_validation", self.doc)

    def test_the_documented_log_and_data_paths_are_the_mounted_volumes(self):
        for path in ("/var/lib/tianshu", "/var/log/tianshu", "/etc/tianshu"):
            self.assertIn(path, self.doc, path)
            self.assertIn(path, self.dockerfile, path)
